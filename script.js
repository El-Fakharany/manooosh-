// 3D Render Loop
function animate() {
  requestAnimationFrame(animate);

  const delta = clock.getDelta();
  const time = clock.getElapsedTime();

  targetX += (mouseX - targetX) * 0.05;
  targetY += (mouseY - targetY) * 0.05;

  if (starsParticles) {
    starsParticles.rotation.y = time * 0.02;
    starsParticles.rotation.x = time * 0.01;
  }

  if (orbitalRing) {
    orbitalRing.rotation.y = time * 0.25;
  }

  if (heartParticles) {
    const beatCycle = time * 2.2;
    const beat = Math.pow(Math.sin(beatCycle), 12) * 0.16 + Math.pow(Math.sin(beatCycle + 0.35), 18) * 0.1;
    
    heartScale += (1.0 - heartScale) * 0.08;
    const finalScale = heartScale + beat;

    heartParticles.scale.set(finalScale, finalScale, finalScale);
    heartParticles.rotation.y = time * 0.35 + targetX * 2 + dragRotationY;
    heartParticles.rotation.x = Math.sin(time * 0.5) * 0.1 + targetY * 2 + dragRotationX;
    heartParticles.position.y = Math.sin(time * 1.5) * 0.8;

    if (innerCoreHeart) {
      innerCoreHeart.scale.set(finalScale * 0.65, finalScale * 0.65, finalScale * 0.65);
      innerCoreHeart.rotation.y = heartParticles.rotation.y;
      innerCoreHeart.rotation.x = heartParticles.rotation.x;
      innerCoreHeart.position.y = heartParticles.position.y + 0.5;
    }
  }

  if (floatingPetalsGroup) {
    floatingPetalsGroup.children.forEach(petal => {
      petal.rotation.x += petal.userData.rotSpeedX;
      petal.rotation.y += petal.userData.rotSpeedY;
      petal.position.y -= petal.userData.fallSpeed;
      petal.position.x += Math.sin(time * petal.userData.swayFreq) * 0.02;

      if (petal.position.y < -25) {
        petal.position.y = 25;
        petal.position.x = (Math.random() - 0.5) * 55;
      }
    });
  }

  renderer.render(scene, camera);
}


