class RomanticAudio {
  constructor() {
    this.ctx = null;
    this.audioElement = null;
    this.isPlaying = false;
  }

  init() {
    if (!this.audioElement) {
      this.audioElement = document.getElementById('bg-music');
      if (this.audioElement) {
        this.audioElement.volume = 0.9;
      }
    }
    if (!this.ctx) {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      this.ctx = new AudioCtx();
    }
    if (this.ctx.state === 'suspended') {
      this.ctx.resume();
    }
  }

  playHeartbeat() {
    this.init();
    const now = this.ctx.currentTime;
    this.thump(now, 72, 0.14);
    this.thump(now + 0.16, 56, 0.18);
  }

  thump(time, freq, duration) {
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(freq, time);
    osc.frequency.exponentialRampToValueAtTime(25, time + duration);

    gain.gain.setValueAtTime(1.0, time);
    gain.gain.exponentialRampToValueAtTime(0.001, time + duration);

    osc.connect(gain);
    gain.connect(this.ctx.destination);

    osc.start(time);
    osc.stop(time + duration);
  }

  playChime() {
    this.init();
    const notes = [523.25, 659.25, 783.99, 1046.50, 1318.51];
    const now = this.ctx.currentTime;
    notes.forEach((freq, idx) => {
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();
      osc.type = 'sine';
      osc.frequency.setValueAtTime(freq, now + idx * 0.07);

      gain.gain.setValueAtTime(0.18, now + idx * 0.07);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + idx * 0.07 + 0.8);

      osc.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start(now + idx * 0.07);
      osc.stop(now + idx * 0.07 + 0.8);
    });
  }

  startSong() {
    this.init();
    if (this.audioElement) {
      this.audioElement.play().then(() => {
        this.isPlaying = true;
        this.updateUI(true);
      }).catch(err => {
        console.log("Waiting for user tap to play song:", err);
      });
    }
  }

  stopSong() {
    if (this.audioElement) {
      this.audioElement.pause();
      this.isPlaying = false;
      this.updateUI(false);
    }
  }

  toggle() {
    this.init();
    if (this.audioElement) {
      if (this.audioElement.paused) {
        this.startSong();
        return true;
      } else {
        this.stopSong();
        return false;
      }
    }
    return false;
  }

  updateUI(playing) {
    const waves = document.getElementById('music-waves');
    const icon = document.getElementById('music-icon');
    const label = document.getElementById('music-status-text');

    if (waves) {
      if (playing) waves.classList.add('active');
      else waves.classList.remove('active');
    }

    if (icon) {
      if (playing) {
        icon.className = 'fa-solid fa-pause music-icon';
      } else {
        icon.className = 'fa-solid fa-play music-icon';
      }
    }

    if (label) {
      label.textContent = playing ? 'شغالة: أغنية باسم منوشتي 🎵💜' : 'تشغيل: أغنية باسم منوشتي 🎵💜';
    }
  }
}

