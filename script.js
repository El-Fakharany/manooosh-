// TYPEWRITER ANIMATION ENGINE
// ==========================================================================
function initTypewriter() {
  const el = document.getElementById('typewriter-text');
  if (!el) return;

  let textIdx = 0;
  let charIdx = 0;
  let isDeleting = false;

  function getCurrentText() {
    const rawTemplate = TYPEWRITER_TEMPLATES[textIdx];
    const daysCount = Math.floor(Math.max(0, Date.now() - new Date(2026, 9, 2, 0, 0, 0).getTime()) / (1000 * 60 * 60 * 24));
    return rawTemplate.replace(/\{DAYS\}/g, daysCount);
  }

  function typeStep() {
    const currentFullText = getCurrentText();

    if (!isDeleting) {
      el.textContent = currentFullText.substring(0, charIdx + 1);
      charIdx++;
      if (charIdx === currentFullText.length) {
        isDeleting = true;
        setTimeout(typeStep, 3500); // Wait after finishing
        return;
      }
      setTimeout(typeStep, 50);
    } else {
      el.textContent = currentFullText.substring(0, charIdx - 1);
      charIdx--;
      if (charIdx === 0) {
        isDeleting = false;
        textIdx = (textIdx + 1) % TYPEWRITER_TEMPLATES.length;
        setTimeout(typeStep, 600);
        return;
      }
      setTimeout(typeStep, 25);
    }
  }

  typeStep();
}


